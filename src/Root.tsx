// The stage is what the viewer plays on, and it is chosen by MECHANIC rather
// than by format — which is why 18 formats do not need 18 templates.
const EpStage: React.FC<{
  episode: EpisodeSpec;
  phase: string;
  revealed: boolean;
  accentColor: string;
  pressureProgress: number;
  hasStill: boolean;
  onLight: boolean;
  headFont: string;
  bodyFont: string;
  hasPresenter: boolean;
}> = ({ episode, phase, revealed, accentColor, pressureProgress, hasStill, onLight,
        headFont, bodyFont, hasPresenter }) => {
  // The question is the show's voice — it carries the brand's header typeface.
  // Choices and figures are UI and stay on the body face for legibility.
  // The presenter owns his beats outright. He appears on the hook and the
  // reveal and he SAYS both, so every element this component draws -- the
  // question, the options, the countdown, the answer band -- would be words
  // printed over a talking face. The caption is drawn elsewhere and stays,
  // because it sits low over a chest rather than across a face.
  if (hasPresenter) return null;

  const font = bodyFont;
  const ink = onLight ? '#111111' : '#FFFFFF';
  const mechanic = episode.mechanic || 'reveal';
  const choices = episode.choices || [];
  const correct = episode.correct_index;

  // Nothing but the hook is on screen during the hook beat: the first frame is
  // the challenge, and a question header competing with it splits attention.
  // On a visual format the IMAGE is the challenge, so it is already behind this.
  if (phase === 'hook') {
    return (
      <AbsoluteFill
        style={{
          // Centred when the hook is the only thing on screen. With a still
          // behind it the hook moves to the top third, because centring it puts
          // the words directly on the subject — which produced an unreadable
          // first frame of black text on a black silhouette.
          justifyContent: hasStill ? 'flex-start' : 'center',
          alignItems: 'center',
          paddingLeft: EP_SAFE_SIDE,
          paddingRight: EP_SAFE_SIDE,
          paddingTop: EP_SAFE_TOP + EP_HEADER_H,
          paddingBottom: EP_SAFE_BOTTOM,
        }}
      >
        <div
          style={{
            fontFamily: headFont, fontSize: hasStill ? 74 : 92, fontWeight: 700,
            color: ink, textAlign: 'center', lineHeight: 1.15,
            textShadow: onLight ? 'none' : '0 6px 24px rgba(0,0,0,0.5)',
            // A plate behind the words so the hook stays legible whatever the
            // still happens to be behind it.
            ...(hasStill
              ? {
                  background: onLight ? 'rgba(255,255,255,0.9)' : 'rgba(0,0,0,0.55)',
                  borderRadius: 24,
                  padding: '22px 30px',
                }
              : {}),
          }}
        >
          {episode.hook}
        </div>
      </AbsoluteFill>
    );
  }

  const Question = (
    <div
      style={{
        fontFamily: headFont, fontSize: 60, fontWeight: 700, color: ink,
        textAlign: 'center', lineHeight: 1.24, marginBottom: 46,
      }}
    >
      {episode.question}
    </div>
  );

  const Choices = (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 22, width: '100%' }}>
      {choices.map((c, i) => {
        const isRight = revealed && correct === i;
        const isWrong = revealed && correct !== null && correct !== i;
        return (
          <div
            key={i}
            style={{
              fontFamily: font, fontSize: 48, fontWeight: 600,
              color: isWrong ? 'rgba(255,255,255,0.35)' : '#FFFFFF',
              background: isRight ? accentColor : 'rgba(255,255,255,0.10)',
              border: `3px solid ${isRight ? accentColor : 'rgba(255,255,255,0.22)'}`,
              borderRadius: 18, padding: '22px 28px', textAlign: 'left',
            }}
          >
            <span style={{ opacity: 0.6, marginRight: 18 }}>
              {String.fromCharCode(65 + i)}
            </span>
            {c}
          </div>
        );
      })}
    </div>
  );

  const Figures = (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 16, width: '100%' }}>
      {(episode.figures || []).map((f, i) => (
        <div
          key={i}
          style={{
            display: 'flex', justifyContent: 'space-between', alignItems: 'center',
            fontFamily: font, fontSize: 48, color: '#FFFFFF',
            background: 'rgba(255,255,255,0.08)', borderRadius: 14,
            padding: '18px 26px',
          }}
        >
          <span style={{ opacity: 0.75 }}>{f.label}</span>
          <span style={{ fontWeight: 700 }}>{f.value}</span>
        </div>
      ))}
    </div>
  );

  // When the answer is one of the choices, highlighting it IS the reveal. A
  // banner underneath repeating the same words is noise on a screen that has
  // seconds to land.
  const answerIsAChoice = choices.length > 0 && correct !== null && correct !== undefined;
  const Answer = revealed && !answerIsAChoice ? (
    <div
      style={{
        fontFamily: font, fontSize: 62, fontWeight: 700, color: '#FFFFFF',
        background: accentColor, borderRadius: 20, padding: '26px 32px',
        textAlign: 'center', marginTop: 34,
      }}
    >
      {episode.answer}
    </div>
  ) : null;

  // The countdown is the moment viewers drop, so it has to LOOK like a clock,
  // not a loading bar. A thin progress line under three spoken words read as a
  // buffering indicator; a ticking ring with the number counting 3-2-1 inside it
  // is the visual language every quiz show already taught the audience.
  const secondsLeft = Math.max(1, Math.ceil((1 - pressureProgress) * 3));
  const ringSize = 190;
  const stroke = 14;
  const radius = (ringSize - stroke) / 2;
  const circumference = 2 * Math.PI * radius;
  const Countdown =
    phase === 'pressure' ? (
      <div style={{ display: 'flex', justifyContent: 'center', marginTop: 46 }}>
        <div style={{ position: 'relative', width: ringSize, height: ringSize }}>
          <svg width={ringSize} height={ringSize} style={{ transform: 'rotate(-90deg)' }}>
            <circle
              cx={ringSize / 2} cy={ringSize / 2} r={radius}
              fill="none" stroke={onLight ? 'rgba(0,0,0,0.12)' : 'rgba(255,255,255,0.18)'}
              strokeWidth={stroke}
            />
            <circle
              cx={ringSize / 2} cy={ringSize / 2} r={radius}
              fill="none" stroke={accentColor} strokeWidth={stroke}
              strokeLinecap="round"
              strokeDasharray={circumference}
              strokeDashoffset={circumference * pressureProgress}
            />
          </svg>
          <div
            style={{
              position: 'absolute', inset: 0, display: 'flex',
              alignItems: 'center', justifyContent: 'center',
              fontFamily: headFont, fontSize: 96, fontWeight: 700, color: ink,
              // A small pulse on each tick so the number reads as counting
              // rather than sitting still.
              transform: `scale(${1 + 0.06 * (1 - ((1 - pressureProgress) * 3) % 1)})`,
            }}
          >
            {secondsLeft}
          </div>
        </div>
      </div>
    ) : null;

  let body: React.ReactNode = null;
  if (mechanic === 'choices' || mechanic === 'verdict' || mechanic === 'ordering') {
    body = choices.length ? Choices : null;
  } else if (mechanic === 'calculation') {
    body = Figures;
  }

  // The menu comes down when the answer goes up. An ordering question whose
  // answer is a SEQUENCE rather than one of the options needs its own band, and
  // stacking that under four choices overran the padding and printed the answer
  // straight through the caption -- two lines of text on the same pixels, both
  // unreadable. Once the answer is on screen the options have done their job.
  if (Answer) {
    body = null;
  }

  // With a still behind it the game moves to the top third, so the picture the
  // viewer is being asked to identify is not covered by the question about it.
  return (
    <AbsoluteFill
      style={{
        justifyContent: hasStill ? 'flex-start' : 'center',
        paddingLeft: EP_SAFE_SIDE,
        paddingRight: EP_SAFE_SIDE,
        paddingTop: EP_SAFE_TOP + EP_HEADER_H,
        paddingBottom: EP_SAFE_BOTTOM + 80,
      }}
    >
      {Question}
      {body}
      {Countdown}
      {Answer}
    </AbsoluteFill>
  );
};

const TriviaEpisodeComp: React.FC<TriviaEpisodeProps> = ({
  episode,
  brand = {},
  brandName = 'Ruoth',
  accentColor = '#C0392B',
  logoUrl,
  siteUrl = '',
  musicUrl,
  musicVolume = 0.14,
  narrationUrl,
}) => {
  const frame = useCurrentFrame();
  // Typography and colour come from the BRAND, not from defaults. Every episode
  // before this rendered in a red that is nowhere in Ruoth's palette, set in
  // Arial while the brand specifies Georgia for headers — because the identity
  // document existed and nothing read it.
  const fonts = brand.fonts || [];
  const headFont = `${fonts[1] || 'Georgia'}, Georgia, serif`;
  const bodyFont = `${fonts[0] || 'Arial'}, Arial, Helvetica, sans-serif`;
  const primary = brand.primary || accentColor;
  const light = brand.light || '#F2F2F2';
  const beats = episode?.beats || [];
  const spans = epTimeline(beats);

  // Past the end of the last beat, HOLD the last beat. The composition can run
  // slightly longer than the beats do (audio padding, the pressure floor), and
  // falling back to index 0 there replayed the HOOK -- presenter, hook question
  // and all -- for the final second, after the answer had already been given.
  const foundIndex = spans.findIndex((s) => frame >= s.from && frame < s.to);
  const activeIndex =
    foundIndex >= 0
      ? foundIndex
      : frame >= (spans[spans.length - 1]?.to ?? 0)
      ? Math.max(0, spans.length - 1)
      : 0;
  const active = beats[activeIndex] || {};
  const phase = String(active.beat || 'hook');
  const revealed = beats
    .slice(0, activeIndex + 1)
    .some((b) => ['reveal', 'payoff', 'cta'].includes(String(b.beat)));

  const span = spans[activeIndex] || { from: 0, to: 1 };
  const pressureProgress = (frame - span.from) / Math.max(1, span.to - span.from);

  const presenter = (episode.presenter_clips || []).find(
    (p) => p.beat_index === activeIndex,
  );

  const hasBeatAudio = beats.some((b) => b.audio_url);

  // ── Sound design ──────────────────────────────────────────────────────────
  // Until now the mix was two layers: a music bed and narration. Grepping the
  // whole composition for whoosh, riser, impact, click, ding or sting returned
  // nothing. Professional short-form feels expensive largely because the EAR is
  // rewarded on every state change, and silence between words is the clearest
  // tell that something was assembled rather than edited.
  //
  // These hang off the BEAT spine, which already exists and is driven by the
  // measured narration, so they need no shot plan and cannot drift.
  const sfx = (() => {
    const out: { src: string; from: number; volume: number; duck: boolean }[] = [];
    beats.forEach((b, i) => {
      const at = spans[i]?.from ?? 0;
      const name = String(b.beat || '');
      if (name === 'hook')
        out.push({ src: 'sfx/hook_impact.wav', from: at, volume: 0.55, duck: true });
      if (name === 'reveal')
        out.push({ src: 'sfx/reveal_impact.wav', from: at, volume: 0.6, duck: true });
      if (name === 'payoff')
        out.push({ src: 'sfx/correct_sting.wav', from: at, volume: 0.4, duck: false });
      if (name === 'cta')
        out.push({ src: 'sfx/cta_chime.wav', from: at, volume: 0.35, duck: false });
      if (name === 'pressure') {
        // One tick per second of the countdown, so the pressure beat is heard
        // as well as seen. The ring already animates; this is what makes it
        // feel like time running out rather than a graphic moving.
        const end = spans[i]?.to ?? at;
        for (let f = at; f < end - EP_FPS * 0.3; f += EP_FPS)
          out.push({ src: 'sfx/countdown_tick.wav', from: Math.round(f), volume: 0.3, duck: false });
      }
    });
    return out;
  })();

  // The two cues that must LAND duck the bed under themselves. Without it the
  // impact fights the music instead of punctuating it — the difference between
  // a mix and a pile of simultaneous sounds.
  const duckWindows = sfx.filter((s) => s.duck).map((s) => [s.from, s.from + Math.round(EP_FPS * 0.9)]);
  const musicAt = (f: number) => {
    for (const [a, b] of duckWindows) {
      if (f >= a && f < b) {
        // Fast drop, slow recovery — how a real ducker behaves.
        const t = (f - a) / (b - a);
        return musicVolume * (0.25 + 0.75 * Math.min(1, Math.max(0, (t - 0.25) / 0.75)));
      }
    }
    return musicVolume;
  };

  // ── The shot plan ─────────────────────────────────────────────────────────
  // Where the episode stops being a slideshow. The Director divides each beat
  // into shots; this finds the one on screen now, and holds the last picture
  // through shots that carry no asset (renderer graphics, which play OVER
  // whatever was there rather than replacing it).
  const shotSpans = epShotTimeline(beats, episode.shots || [], spans);
  const activeShotIdx = shotSpans.findIndex((s) => frame >= s.from && frame < s.to);

  // The last shot at or before now that actually carries a picture. Without
  // this, every question card and countdown would black the frame out.
  const pictureShot = (() => {
    if (!shotSpans.length) return null;
    const upto = activeShotIdx >= 0 ? activeShotIdx : shotSpans.length - 1;
    for (let i = upto; i >= 0; i--) {
      if (shotSpans[i].shot.media_url) return shotSpans[i];
    }
    return null;
  })();

  // On a visual format the picture IS the challenge, so it sits behind every
  // beat from frame 0 — the viewer must never wait for the thing they are being
  // asked to identify.
  //
  // A silhouette quiz stays silhouetted until the reveal, then resolves to the
  // real photograph. That is the format's whole payoff, and it is one CSS
  // filter rather than a second generated image.
  const totalFrames = spans.length ? spans[spans.length - 1].to : 1;
  // Two stills, swapped at the reveal. Section 13 asks the screen to change
  // meaningfully every second or two; one image held for the whole episode
  // reads as a slide however slowly it pushes, and the reveal is the beat the
  // episode is built towards — changing the picture there is where the change
  // is worth the most.
  const setupStill = episode.image_url ? resolveMedia(episode.image_url) : undefined;
  const revealStill = episode.reveal_image_url
    ? resolveMedia(episode.reveal_image_url)
    : undefined;
  const still = revealed && revealStill ? revealStill : setupStill;
  const isSilhouette = episode.format === 'silhouette_quiz';
  // The silhouette field is light until the reveal, so white text would vanish
  // into it. Everything else in the composition sits on dark.
  const onLight = Boolean(still) && isSilhouette && !revealed;

  return (
    <AbsoluteFill style={{ backgroundColor: '#0B0B0C' }}>
      {musicUrl ? <Audio src={resolveMedia(musicUrl)!} volume={musicAt} loop /> : null}

      {/* Sound design. Local files, baked into the render image — a remote
          fetch during a render is a single point of failure, and an episode
          that loses its audio bed to a network blip is a failed episode. */}
      {sfx.map((s, i) => (
        <Sequence key={`sfx-${i}`} from={s.from}>
          <Audio src={staticFile(s.src)} volume={s.volume} />
        </Sequence>
      ))}

      {still && isSilhouette ? (
        // A silhouette is an ISOLATED object on a light field, never a
        // full-bleed photo: `cover` plus brightness(0) fills the frame with
        // black and shows the viewer nothing. The still carries a real alpha
        // channel, so blackening it leaves only the shape. At the reveal the
        // filter lifts and the same asset becomes the photograph — which is the
        // whole payoff of the format, from one image.
        <AbsoluteFill style={{ backgroundColor: revealed ? '#0B0B0C' : light }}>
          {/* Sits in the lower two-thirds: the question and captions own the top
              and bottom bands, and the shape must not compete with either. */}
          <AbsoluteFill
            style={{
              justifyContent: 'center', alignItems: 'center',
              paddingTop: 420, paddingBottom: 340, paddingLeft: 80, paddingRight: 80,
            }}
          >
            <Img
              src={still}
              style={{
                maxWidth: '92%', maxHeight: '100%', objectFit: 'contain',
                filter: revealed ? 'none' : 'brightness(0)',
              }}
            />
          </AbsoluteFill>
        </AbsoluteFill>
      ) : pictureShot ? (
        (() => {
          // THE DIRECTED PATH. One picture per shot, each with its own planned
          // motion, cutting every second or two — instead of one still held for
          // thirty-five seconds under a slow linear zoom, which is what every
          // published episode was.
          const { shot, from, to } = pictureShot;
          const shotFrames = Math.max(1, to - from);
          const t = Math.min(1, Math.max(0, (frame - from) / shotFrames));
          const { transform, filter } = epMotion(shot.motion, t, shotFrames);
          const url = resolveMedia(shot.media_url!)!;
          const isVideo = /\.(mp4|mov|webm)(\?|$)/i.test(shot.media_url!);
          const style = {
            width: '100%', height: '100%', objectFit: 'cover' as const,
            transform, filter,
          };
          return (
            <AbsoluteFill>
              {/* Keyed on the shot so a cut is a real cut: without the key,
                  React reuses the element and the browser cross-fades the
                  source swap, which turns every planned cut into a dissolve. */}
              {isVideo
                ? <OffthreadVideo key={`${from}`} src={url} style={style} muted />
                : <Img key={`${from}`} src={url} style={style} />}
              {/* Scrim: captions and choices must stay readable over any photo.
                  Lighter than the old one — the art direction now delivers its
                  own deep shadows, so the heavy gradient that rescued flat
                  `low`-quality images just muddies a graded frame. */}
              <AbsoluteFill
                style={{
                  background:
                    'linear-gradient(to bottom, rgba(0,0,0,0.40) 0%, rgba(0,0,0,0.05) 35%, rgba(0,0,0,0.62) 100%)',
                }}
              />
            </AbsoluteFill>
          );
        })()
      ) : still ? (
        <AbsoluteFill>
          {/* THE LEGACY PATH, kept so re-rendering an older episode that has no
              shot plan still works. A held still reads as a slide, so a slow
              push at least keeps the frame alive. */}
          <Img
            src={still}
            style={{
              width: '100%',
              height: '100%',
              objectFit: 'cover',
              transform: `scale(${interpolate(
                frame,
                [0, Math.max(1, totalFrames)],
                [1, 1.12],
                { extrapolateLeft: 'clamp', extrapolateRight: 'clamp' },
              )})`,
            }}
          />
          <AbsoluteFill
            style={{
              background:
                'linear-gradient(to bottom, rgba(0,0,0,0.55) 0%, rgba(0,0,0,0.15) 35%, rgba(0,0,0,0.75) 100%)',
            }}
          />
        </AbsoluteFill>
      ) : null}

      {/* Per-beat narration, each starting exactly where its beat starts. */}
      {hasBeatAudio
        ? beats.map((b, i) =>
            b.audio_url ? (
              <Sequence key={i} from={spans[i].from} durationInFrames={spans[i].to - spans[i].from}>
                {/* resolveMedia, not the raw URL: CI downloads every asset up
                    front and passes bare filenames, because a fetch that fails
                    mid-render kills an otherwise finished episode. */}
                <Audio src={resolveMedia(b.audio_url)!} />
              </Sequence>
            ) : null,
          )
        : narrationUrl
        ? <Audio src={resolveMedia(narrationUrl)!} />
        : null}

      {/* The presenter is the BACKDROP for its beat, not a panel on top of one.
          HeyGen renders a stock video avatar at the full 1080x1920 already
          standing in this episode's own still, so the clip is the whole picture
          and it covers the frame edge to edge.

          It used to be drawn at its own shape over a dimmed copy of the scene.
          That was written for photo-avatar looks, which come back 16:9 and only
          cover a band. On a full-height video avatar it put HIS copy of the
          still, at a different scale and brightness, on top of the episode's
          copy -- so the clip read as a lit rectangle pasted over the frame and
          the presenter appeared to float. Covering the frame removes the seam;
          there is nothing left to dim, so the scrim is gone too.

          Wrapped in a Sequence so the clip plays from ITS OWN first frame.
          Without it the clip runs on composition time: a reveal presenter a
          couple of hundred frames in was already past the end of its clip, so
          Remotion held the last frame and the avatar stood there staring. */}
      {presenter ? (
        <Sequence from={span.from} layout="none">
          <AbsoluteFill>
            <OffthreadVideo
              src={resolveMedia(presenter.video_url)!}
              style={{ width: '100%', height: '100%', objectFit: 'cover' }}
              muted
            />

            {/* ── Anchoring the presenter in the room ────────────────────────
                HeyGen hands back a finished 1080x1920 frame with the avatar
                already over this episode's still, so we cannot touch the key.
                What we CAN do is everything a compositor does after the key,
                and without it he reads as a cut-out: lit flat and bright
                against a warm, dark, side-lit scene, no shadow under him, and
                nothing in front of him — so he floats rather than stands.

                Four passes, in the order a grade would apply them. All are
                gradients over the finished clip: no extra render cost, no API
                call, and nothing here touches the avatar itself. */}

            {/* 1. LIGHT DIRECTION. The scene is lit from frame left with deep
                   fall-off to the right; the avatar arrives evenly lit. This
                   re-imposes the scene's own key so the two agree. */}
            <AbsoluteFill
              style={{
                background:
                  'linear-gradient(100deg, rgba(255,196,120,0.16) 0%, ' +
                  'rgba(255,170,90,0.05) 34%, rgba(0,0,0,0) 55%, ' +
                  'rgba(0,0,0,0.30) 88%, rgba(0,0,0,0.46) 100%)',
                mixBlendMode: 'soft-light',
              }}
            />

            {/* 2. GRADE. Pulls his whites out of daylight and into the
                   episode's amber, the same shift the stills already carry. */}
            <AbsoluteFill
              style={{
                background: 'rgba(196,116,44,0.14)',
                mixBlendMode: 'color',
              }}
            />

            {/* 2b. HIGHLIGHT RESTRAINT. A white chef's jacket arrives as the
                   brightest object in a frame whose stills are graded for
                   rich blacks and restrained highlights, so he reads as lit
                   by a different production. Multiply pulls only the bright
                   values down and leaves the shadows alone — the whites land
                   in the scene's amber instead of glowing over it. */}
            <AbsoluteFill
              style={{
                background:
                  'linear-gradient(to top, rgba(150,96,44,0.42) 0%, ' +
                  'rgba(168,112,56,0.34) 45%, rgba(190,140,88,0.22) 100%)',
                mixBlendMode: 'multiply',
              }}
            />

            {/* 3. CONTACT SHADOW. A body standing in a room occludes the
                   light reaching the surface it stands on. Without this the
                   eye gets no depth cue at all and reads him as a sticker. */}
            <AbsoluteFill
              style={{
                background:
                  'radial-gradient(120% 42% at 50% 104%, rgba(0,0,0,0.72) 0%, ' +
                  'rgba(0,0,0,0.40) 42%, rgba(0,0,0,0) 72%)',
              }}
            />

            {/* 4. FOREGROUND OCCLUSION — the single strongest "he is in the
                   room" cue. Something out of focus sits between camera and
                   subject, so the frame has depth in front of him as well as
                   behind. Deliberately soft and dark: it must read as a
                   surface the shot is looking over, never as a bar. */}
            <AbsoluteFill
              style={{
                background:
                  'linear-gradient(to top, rgba(18,12,8,0.92) 0%, ' +
                  'rgba(24,16,10,0.78) 5%, rgba(30,20,12,0.34) 11%, ' +
                  'rgba(0,0,0,0) 17%)',
                filter: 'blur(6px)',
              }}
            />

            {/* 5. Optical vignette, matching the 50mm the stills are shot on.
                   Ties his edges into the frame instead of leaving them the
                   brightest thing in it. */}
            <AbsoluteFill
              style={{
                background:
                  'radial-gradient(78% 62% at 50% 42%, rgba(0,0,0,0) 55%, ' +
                  'rgba(0,0,0,0.34) 88%, rgba(0,0,0,0.52) 100%)',
              }}
            />
          </AbsoluteFill>
        </Sequence>
      ) : null}

      {/* When the presenter is on screen the frame is HIS. He is on the hook
          and the reveal only, and on both he is saying the words -- so
          printing them over him is redundant text on a face. Two attempts to
          make that readable (a graded band, then reframing him downward) both
          treated the symptom: the text was still in front of the presenter.
          The question carries the middle beats, where there is no one to
          stand in front of. Captions stay: a caption sits low, over a chest,
          which is where broadcast has always put them. */}
      <EpStage
        episode={episode}
        phase={phase}
        revealed={revealed}
        accentColor={primary}
        pressureProgress={pressureProgress}
        hasStill={Boolean(still)}
        onLight={onLight}
        headFont={headFont}
        bodyFont={bodyFont}
        hasPresenter={Boolean(presenter)}
      />

      {/* The hook beat carries no caption: it is already the whole screen. */}
      {phase === 'hook' ? null : (
        <EpCaption
          text={String(active.display || '')}
          accentColor={primary}
          bottom={EP_SAFE_BOTTOM}
          onLight={onLight}
          bodyFont={bodyFont}
        />
      )}

      {/* Persistent brand mark — present in every frame, selling in none of
          them. Never on the hook beat, where it would cost the first second. */}
      {phase === 'hook' ? null : (
        <AbsoluteFill style={{ justifyContent: 'flex-start', alignItems: 'flex-end', padding: 36, paddingTop: EP_SAFE_TOP }}>
          {logoUrl ? (
            <Img
              src={resolveMedia(logoUrl)!}
              style={{
                width: 150, opacity: 0.95,
                // A dark logo vanishes on the silhouette's light field and a
                // light one vanishes on everything else. A soft plate behind it
                // keeps the mark legible on both without touching the artwork.
                background: onLight ? 'rgba(255,255,255,0.75)' : 'rgba(0,0,0,0.35)',
                borderRadius: 12, padding: 8,
              }}
            />
          ) : (
            <div style={{ fontFamily: headFont, fontSize: 30, color: onLight ? 'rgba(0,0,0,0.55)' : 'rgba(255,255,255,0.7)', fontWeight: 600 }}>
              {brandName}
            </div>
          )}
        </AbsoluteFill>
      )}

      {/* Section 15: the brand stays visually present in EVERY episode, while
          explicit selling stays limited. The site sat under the logo only on
          the CTA beat, so the 15% no-CTA control and every non-product episode
          gave a viewer no way to find the shop at all. It now rides under the
          mark throughout — small, quiet, never covering the game — and steps
          forward only on the CTA beat. */}
      {siteUrl && phase !== 'hook' ? (
        <AbsoluteFill
          style={{
            justifyContent: 'flex-start', alignItems: 'flex-end', padding: 36,
            paddingTop: EP_SAFE_TOP + (logoUrl
              ? EP_SITE_OFFSET_WITH_LOGO
              : EP_SITE_OFFSET_TEXT_ONLY),
          }}
        >
          <div
            style={{
              fontFamily: bodyFont,
              fontSize: phase === 'cta' ? 34 : 24,
              fontWeight: 600,
              letterSpacing: 0.4,
              color: onLight
                ? `rgba(0,0,0,${phase === 'cta' ? 0.8 : 0.5})`
                : `rgba(255,255,255,${phase === 'cta' ? 0.95 : 0.62})`,
              background: phase === 'cta'
                ? (onLight ? 'rgba(255,255,255,0.85)' : 'rgba(0,0,0,0.45)')
                : 'transparent',
              borderRadius: 10,
              padding: phase === 'cta' ? '8px 14px' : 0,
            }}
          >
            {siteUrl}
          </div>
        </AbsoluteFill>
      ) : null}
    </AbsoluteFill>
  );
};

