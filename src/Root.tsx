// ── TriviaEpisode ────────────────────────────────────────────────────────────
// The retention rebuild of TriviaReel.
//
// TriviaReel narrated a statement: branded intro card, question, answer, end
// card. There was nothing to stay for, because the viewer was told a fact rather
// than given something to solve — and the first two seconds, which is the entire
// decision window, were spent on a logo.
//
// This composition renders a GAME laid out on a beat timeline:
//   hook       frame 0. No logo, no greeting. The challenge lands immediately.
//   challenge  what the viewer has to solve.
//   clue       progressive narrowing, 1-3 beats.
//   pressure   countdown — the moment before the answer.
//   reveal     the answer, visually unmistakable.
//   payoff     why it is correct. This is the beat that builds authority.
//   cta        one action, and only when a CTA type was assigned.
//
// Beat durations come from real measured narration, not estimates, so captions
// and reveals land on the voice. GENERIC: the mechanic decides the stage, so one
// composition serves every format, and every brand string arrives as a prop.

type EpisodeBeat = {
  beat: string;
  spoken?: string;
  display?: string;
  audio_url?: string | null;
  duration_seconds?: number | null;
};

type PresenterClip = {
  beat_index: number;
  beat?: string;
  video_url: string;
  duration_seconds?: number | null;
};

// One slice of one beat, planned by the Episode Director in beia_core.
//
// The shot plan drives the BACKGROUND: what picture is on screen and how it
// moves. The game layer (question, options, countdown, answer) stays beat-driven
// in EpStage, which is how broadcast trivia actually works — the question holds
// while the pictures cut behind it.
//
// Weights, never seconds. The Director cannot know how long a beat runs because
// that comes from the measured mp3; it says only how the beat DIVIDES. A plan in
// absolute seconds would desync the moment the voice came back longer than
// predicted, and a desynced episode plays the answer over the question.
type EpisodeShot = {
  beat_index: number;
  beat: string;
  shot_type: string;
  media_kind: string;
  weight: number;
  motion: string;
  sound_cue?: string | null;
  owns_frame?: boolean;
  //: Filled by the asset step. Absent for renderer graphics, which have no
  //: asset — those shots hold whatever picture was last on screen while the
  //: graphic plays over it.
  media_url?: string | null;
};

type EpisodeSpec = {
  format?: string;
  mechanic?: string;
  pillar?: string;
  difficulty?: string;
  hook?: string;
  question?: string;
  answer?: string;
  payoff?: string;
  choices?: string[];
  correct_index?: number | null;
  correct_order?: number[] | null;
  figures?: { label: string; value: string }[];
  cta_type?: string;
  cta?: string;
  visual_brief?: string;
  image_url?: string | null;
  reveal_image_url?: string | null;
  beats?: EpisodeBeat[];
  avatar_treatment?: string;
  presenter_clips?: PresenterClip[];
  duration_target?: number[];
  //: The shot plan. Absent on older episodes, which fall back to the single
  //: held still — the whole point of keeping that path alive is that a
  //: re-render of an old episode must not break.
  shots?: EpisodeShot[];
};

type BrandIdentity = {
  primary?: string;
  secondary?: string;
  light?: string;
  palette?: string[];
  fonts?: string[];
  tagline?: string;
};

type TriviaEpisodeProps = {
  episode: EpisodeSpec;
  brand?: BrandIdentity;
  brandName?: string;
  accentColor?: string;
  logoUrl?: string;
  siteUrl?: string;
  musicUrl?: string;
  musicVolume?: number;
  narrationUrl?: string; // single fallback track when there is no per-beat audio
};

const EP_FPS = 30;

// Platform chrome, measured against a real Shorts screenshot rather than
// guessed. YouTube puts the back arrow, search and menu across the top and the
// channel handle, description and action rail across the bottom — an episode
// published with the question under the back arrow and the caption colliding
// with the handle. TikTok and Instagram are worse at the bottom, so these are
// sized for the worst case and used everywhere.
const EP_SAFE_TOP = 300;      // ~16% of 1920
const EP_SAFE_BOTTOM = 520;   // ~27% — the action rail and description sit here
const EP_SAFE_SIDE = 96;
// The brand mark and store URL sit in a strip of their own under the safe top.
// Content has to start below it: both used to begin at EP_SAFE_TOP, so a long
// question wrapped straight through "Ruoth" and "ruothstore.com".
// Tall enough to clear a logo (150 wide plus its plate) AND the store URL that
// rides under it. It was 150, which cleared the text-only mark but not a logo.
const EP_HEADER_H = 220;
// The URL sits under whichever mark is above it. At a flat 84 it landed on top
// of the logo, which is why "ruothstore.com" appeared stamped across it.
const EP_SITE_OFFSET_WITH_LOGO = 178;
const EP_SITE_OFFSET_TEXT_ONLY = 84;

// Speech rate measured from real narration takes, used ONLY when a beat has no
// measured audio (the free-voice fallback path). Deliberately a named constant:
// a wrong value here desyncs every beat after it.
const EP_WORDS_PER_SECOND = 2.4;
const EP_MIN_BEAT_SECONDS = 0.9;

const epBeatSeconds = (b: EpisodeBeat): number => {
  if (b.duration_seconds && b.duration_seconds > 0) return b.duration_seconds;
  const words = (b.spoken || b.display || '').trim().split(/\s+/).filter(Boolean).length;
  return Math.max(EP_MIN_BEAT_SECONDS, words / EP_WORDS_PER_SECOND);
};

// Beat index -> [startFrame, endFrame). One source of truth for timing, shared
// by the audio, the stage and the captions so they cannot drift apart.
// The countdown must actually last as long as it says. Narration of "three,
// two, one" takes about 1.5 seconds, so a ring driven purely by speech counted
// 3-2-1 in half the time and gave the viewer no chance to answer — the pressure
// beat is precisely where they are supposed to be deciding.
const EP_MIN_PRESSURE_SECONDS = 3.2;

// Divide each beat's REAL duration among the shots planned for it, by weight.
// Returns one span per shot, in play order. A beat with no shots gets none, and
// the background simply holds — which is the old behaviour, so an episode
// planned without shots still renders.
const epShotTimeline = (
  beats: EpisodeBeat[],
  shots: EpisodeShot[],
  beatSpans: { from: number; to: number }[],
) => {
  const out: { shot: EpisodeShot; from: number; to: number }[] = [];
  for (let i = 0; i < beats.length; i++) {
    const mine = shots.filter((s) => s.beat_index === i);
    if (!mine.length) continue;
    const span = beatSpans[i];
    if (!span) continue;
    const total = mine.reduce((a, s) => a + (s.weight > 0 ? s.weight : 1), 0) || 1;
    let at = span.from;
    mine.forEach((s, k) => {
      const w = s.weight > 0 ? s.weight : 1;
      // The last shot absorbs the rounding, so the shots of a beat always sum
      // to exactly the beat. Rounding each independently left one-frame gaps
      // that flash the layer underneath.
      const to = k === mine.length - 1
        ? span.to
        : Math.min(span.to, at + Math.round(((span.to - span.from) * w) / total));
      out.push({ shot: s, from: at, to: Math.max(at + 1, to) });
      at = to;
    });
  }
  return out;
};

// The motion vocabulary, as the renderer's half of the contract with the
// Director. Every name in `trivia_visual_taxonomy.MOTIONS` must resolve here —
// a Director free to plan motion the renderer silently ignores is exactly the
// failure mode where the pipeline reports success and the video is static.
//
// `t` is progress through the shot, 0..1. Returns a CSS transform plus an
// optional filter.
const epMotion = (
  motion: string, t: number, shotFrames: number,
): { transform: string; filter?: string } => {
  // Moves are specified in ms in the taxonomy; convert once, here.
  const atMs = (ms: number) => Math.min(1, (t * shotFrames) / ((ms / 1000) * EP_FPS));
  const ease = (x: number) => 1 - Math.pow(1 - x, 3);       // ease_out cubic
  const back = (x: number) => 1 + 2.7 * Math.pow(x - 1, 3) + 1.7 * Math.pow(x - 1, 2);

  switch (motion) {
    case 'push_in':
      return { transform: `scale(${1 + 0.10 * t})` };
    case 'pull_out':
      return { transform: `scale(${1.10 - 0.10 * t})` };
    case 'punch_in': {
      const p = ease(atMs(220));
      return { transform: `scale(${1.08 - 0.08 * p})` };
    }
    case 'whip_left': {
      const p = ease(atMs(260));
      return {
        transform: `translateX(${-14 * (1 - p)}%) scale(${1.04 - 0.04 * p})`,
        filter: p < 1 ? `blur(${10 * (1 - p)}px)` : undefined,
      };
    }
    case 'slide_up': {
      const p = ease(atMs(320));
      return { transform: `translateY(${60 * (1 - p)}px)` };
    }
    case 'pop': {
      const p = atMs(260);
      return { transform: `scale(${0.9 + 0.1 * back(p)})` };
    }
    case 'shake': {
      const p = atMs(380);
      const amp = 10 * (1 - p);
      return { transform: `translateX(${Math.sin(p * Math.PI * 6) * amp}px)` };
    }
    case 'pulse': {
      const beat = (t * shotFrames) / (0.6 * EP_FPS);
      return { transform: `scale(${1 + 0.03 * Math.abs(Math.sin(beat * Math.PI))})` };
    }
    case 'glow':
      return { transform: 'scale(1)', filter: `brightness(${1 + 0.25 * (1 - ease(atMs(520)))})` };
    case 'hold':
    case 'cut':
    default:
      return { transform: 'scale(1)' };
  }
};

const epTimeline = (beats: EpisodeBeat[]) => {
  let at = 0;
  return beats.map((b) => {
    let seconds = epBeatSeconds(b);
    if (String(b.beat) === 'pressure') {
      seconds = Math.max(seconds, EP_MIN_PRESSURE_SECONDS);
    }
    const dur = Math.max(1, Math.round(seconds * EP_FPS));
    const span = { from: at, to: at + dur };
    at += dur;
    return span;
  });
};

export const triviaEpisodeFrames = (episode: EpisodeSpec): number => {
  const beats = episode?.beats || [];
  if (!beats.length) return 30 * EP_FPS;
  const spans = epTimeline(beats);
  // A held final frame stops the last word being clipped by the encoder.
  return spans[spans.length - 1].to + Math.round(0.6 * EP_FPS);
};

