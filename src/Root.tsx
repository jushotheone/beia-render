import React from 'react';
import {
  Composition, useCurrentFrame, Img, staticFile,
  AbsoluteFill, Sequence, OffthreadVideo, Audio, interpolate,
} from 'remotion';
import { getVideoMetadata } from '@remotion/media-utils';

// Generic BEIA reel: renders a vertical (1080x1920) reel from a list of card
// image URLs. Brand look (end-card name + accent colour) comes in as props so
// the one composition serves every brand — values supplied by beia_core from
// brand config at render time. Nothing here is brand-specific.

const CARD_DURATION = 150; // 5s @ 30fps
const FADE_DURATION = 20;

type ReelProps = {
  images: string[];
  brandName?: string;
  accentColor?: string;
};

const QuoteVideo: React.FC<ReelProps> = ({
  images,
  brandName = 'BEIA',
  accentColor = '#F97316',
}) => {
  const frame = useCurrentFrame();
  const totalFrames = images.length * CARD_DURATION;
  const currentCardIndex = Math.floor(frame / CARD_DURATION);
  const frameInCard = frame % CARD_DURATION;

  let opacity = 1;
  if (frameInCard < FADE_DURATION) {
    opacity = frameInCard / FADE_DURATION;
  } else if (frameInCard > CARD_DURATION - FADE_DURATION) {
    opacity = (CARD_DURATION - frameInCard) / FADE_DURATION;
  }

  const scale = 1 + (frameInCard / CARD_DURATION) * 0.02;
  const progress = frame / totalFrames;

  if (currentCardIndex >= images.length) {
    return (
      <AbsoluteFill style={{ backgroundColor: '#FFFFFF' }}>
        <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'center', height: '100%' }}>
          <p style={{ fontSize: 24, color: '#333' }}>{brandName}</p>
        </div>
      </AbsoluteFill>
    );
  }

  return (
    <AbsoluteFill style={{ backgroundColor: '#FFFFFF' }}>
      <div style={{
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        height: '100%',
        opacity,
        transform: `scale(${scale})`,
      }}>
        <Img
          src={images[currentCardIndex].startsWith('http') ? images[currentCardIndex] : staticFile(images[currentCardIndex])}
          style={{ width: '100%', height: '100%', objectFit: 'contain' }}
        />
      </div>
      <div style={{
        position: 'absolute',
        bottom: 40,
        left: 40,
        right: 40,
        height: 4,
        backgroundColor: 'rgba(0,0,0,0.1)',
        borderRadius: 2,
      }}>
        <div style={{
          width: `${progress * 100}%`,
          height: '100%',
          backgroundColor: accentColor,
          borderRadius: 2,
        }} />
      </div>
    </AbsoluteFill>
  );
};

const DEFAULT_IMAGES = [
  'quotes/quote1.png',
  'quotes/quote2.png',
  'quotes/quote3.png',
];

// ── HookIntroReel ────────────────────────────────────────────────────────────
// The Ruoth (and any brand's) repurpose short: a ~3s white card with the hook
// typed in (typewriter), then the base campaign video cuts in. GENERIC — the hook
// text, the base video URL and the brand accent all come in as props from
// beia_core (the hook is generated by the scheduler; the base mp4 is the brand's
// asset). Nothing here is brand-specific.

const INTRO_FRAMES = 90; // 3s @ 30fps
const TYPE_FRAMES = 60;  // hook fully typed by 2s

type HookReelProps = {
  hook: string;
  videoUrl: string;
  brandName?: string;
  accentColor?: string;
  musicUrl?: string;     // royalty-free track baked over the whole reel (optional)
  musicVolume?: number;  // 0..1 (kept moderate so any clip audio still reads)
};

const TypewriterHook: React.FC<{ hook: string; accentColor: string }> = ({ hook, accentColor }) => {
  const frame = useCurrentFrame();
  const chars = Math.floor(
    interpolate(frame, [0, TYPE_FRAMES], [0, hook.length], {
      extrapolateLeft: 'clamp',
      extrapolateRight: 'clamp',
    })
  );
  const shown = hook.slice(0, chars);
  const cursorOn = Math.floor(frame / 8) % 2 === 0;
  return (
    <AbsoluteFill
      style={{
        backgroundColor: '#FFFFFF',
        alignItems: 'center',
        justifyContent: 'center',
        padding: 90,
      }}
    >
      <p
        style={{
          fontSize: 76,
          fontWeight: 700,
          color: '#111111',
          textAlign: 'center',
          lineHeight: 1.2,
          fontFamily: 'Arial, Helvetica, sans-serif',
          margin: 0,
        }}
      >
        {shown}
        <span style={{ color: accentColor, opacity: cursorOn ? 1 : 0 }}>|</span>
      </p>
    </AbsoluteFill>
  );
};

const HookIntroReel: React.FC<HookReelProps> = ({
  hook,
  videoUrl,
  accentColor = '#C0392B',
  musicUrl,
  musicVolume = 0.4,
}) => {
  return (
    <AbsoluteFill style={{ backgroundColor: '#FFFFFF' }}>
      {musicUrl ? <Audio src={musicUrl} volume={musicVolume} loop /> : null}
      <Sequence durationInFrames={INTRO_FRAMES}>
        <TypewriterHook hook={hook} accentColor={accentColor} />
      </Sequence>
      <Sequence from={INTRO_FRAMES}>
        <AbsoluteFill style={{ backgroundColor: '#000000' }}>
          <OffthreadVideo
            src={videoUrl}
            style={{ width: '100%', height: '100%', objectFit: 'contain' }}
          />
        </AbsoluteFill>
      </Sequence>
    </AbsoluteFill>
  );
};

// ── TriviaReel ───────────────────────────────────────────────────────────────
// The CREATION surface (as opposed to HookIntroReel, which repurposes an
// existing clip). Manufactures a faceless trivia Short from text alone:
// branded intro -> question -> answer reveal -> CTA, narrated by a free
// CPU-only TTS voice with kinetic captions synced to it. GENERIC — every
// brand string comes in as a prop, so any brand reuses this composition.

type Caption = { text: string; startMs: number; endMs: number };

type TriviaReelProps = {
  question: string;
  answer: string;
  pillar?: string;
  narrationUrl?: string;   // absolute URL, else staticFile('narration.wav')
  captions?: Caption[];
  brandName?: string;
  accentColor?: string;
  logoUrl?: string;
  siteUrl?: string;
  musicUrl?: string;
  musicVolume?: number;
};

const TRIVIA_FPS = 30;
const TRIVIA_INTRO_FRAMES = 60;   // 2s branded intro
const TRIVIA_OUTRO_FRAMES = 60;   // 2s CTA end card

const KineticCaptions: React.FC<{ captions: Caption[]; accentColor: string }> = ({
  captions,
  accentColor,
}) => {
  const frame = useCurrentFrame();
  const ms = (frame / TRIVIA_FPS) * 1000;
  const active = captions.find((c) => ms >= c.startMs && ms <= c.endMs);
  if (!active) return null;

  // Pop in over the first 120ms of the caption.
  const since = ms - active.startMs;
  const scale = interpolate(since, [0, 120], [0.92, 1], {
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp',
  });

  return (
    <AbsoluteFill
      style={{
        justifyContent: 'flex-end',
        alignItems: 'center',
        paddingBottom: 320,
      }}
    >
      <div
        style={{
          transform: `scale(${scale})`,
          maxWidth: '84%',
          textAlign: 'center',
          fontFamily: 'Arial, Helvetica, sans-serif',
          fontSize: 62,
          fontWeight: 700,
          lineHeight: 1.25,
          color: '#FFFFFF',
          textShadow: '0 4px 18px rgba(0,0,0,0.55)',
          background: 'rgba(0,0,0,0.42)',
          borderRadius: 24,
          padding: '18px 30px',
          borderBottom: `6px solid ${accentColor}`,
        }}
      >
        {active.text}
      </div>
    </AbsoluteFill>
  );
};

const TriviaReel: React.FC<TriviaReelProps> = ({
  question,
  answer,
  pillar = '',
  narrationUrl,
  captions = [],
  brandName = 'Ruoth',
  accentColor = '#C0392B',
  logoUrl,
  siteUrl = '',
  musicUrl,
  musicVolume = 0.16,
}) => {
  const frame = useCurrentFrame();
  const font = 'Arial, Helvetica, sans-serif';

  // Answer reveals for the last third of the narrated body.
  const narrationFrames = captions.length
    ? Math.round((captions[captions.length - 1].endMs / 1000) * TRIVIA_FPS)
    : 8 * TRIVIA_FPS;
  const revealAt = TRIVIA_INTRO_FRAMES + Math.round(narrationFrames * 0.62);
  const revealed = frame >= revealAt;

  const audioSrc = narrationUrl || staticFile('narration.wav');

  return (
    <AbsoluteFill style={{ backgroundColor: '#0E0E0E' }}>
      {musicUrl ? <Audio src={musicUrl} volume={musicVolume} loop /> : null}
      <Sequence from={TRIVIA_INTRO_FRAMES}>
        <Audio src={audioSrc} />
      </Sequence>

      {/* Branded intro */}
      <Sequence durationInFrames={TRIVIA_INTRO_FRAMES}>
        <AbsoluteFill
          style={{
            backgroundColor: '#FFFFFF',
            justifyContent: 'center',
            alignItems: 'center',
            padding: 80,
          }}
        >
          {logoUrl ? (
            <Img src={logoUrl} style={{ width: 260, marginBottom: 40 }} />
          ) : null}
          <div
            style={{
              fontFamily: font,
              fontSize: 60,
              fontWeight: 700,
              color: '#111111',
              textAlign: 'center',
              letterSpacing: 2,
            }}
          >
            {brandName.toUpperCase()} RECIPE TRIVIA
          </div>
          {pillar ? (
            <div
              style={{
                fontFamily: font,
                fontSize: 40,
                marginTop: 20,
                color: accentColor,
                fontWeight: 600,
              }}
            >
              {pillar}
            </div>
          ) : null}
        </AbsoluteFill>
      </Sequence>

      {/* Question + answer reveal, captions over the top */}
      <Sequence from={TRIVIA_INTRO_FRAMES}>
        <AbsoluteFill style={{ padding: 80, justifyContent: 'flex-start' }}>
          <div
            style={{
              fontFamily: font,
              fontSize: 68,
              fontWeight: 700,
              color: '#FFFFFF',
              lineHeight: 1.3,
              marginTop: 140,
              textAlign: 'center',
            }}
          >
            {question}
          </div>
          {revealed ? (
            <div
              style={{
                fontFamily: font,
                fontSize: 58,
                fontWeight: 700,
                color: accentColor,
                textAlign: 'center',
                marginTop: 60,
                background: 'rgba(255,255,255,0.96)',
                borderRadius: 20,
                padding: '24px 30px',
              }}
            >
              {answer}
            </div>
          ) : null}
        </AbsoluteFill>
        <KineticCaptions captions={captions} accentColor={accentColor} />
      </Sequence>

      {/* CTA end card */}
      <Sequence from={TRIVIA_INTRO_FRAMES + narrationFrames}>
        <AbsoluteFill
          style={{
            backgroundColor: '#FFFFFF',
            justifyContent: 'center',
            alignItems: 'center',
          }}
        >
          {logoUrl ? (
            <Img src={logoUrl} style={{ width: 300, marginBottom: 36 }} />
          ) : null}
          <div style={{ fontFamily: font, fontSize: 52, color: accentColor, fontWeight: 700 }}>
            {siteUrl}
          </div>
        </AbsoluteFill>
      </Sequence>
    </AbsoluteFill>
  );
};

// ── OfferCard ────────────────────────────────────────────────────────────────
// The SELLING creative surface: a flexible product/offer card (still PNG) the
// design team can compose into any layout. GENERIC — every field comes in as a
// design spec prop authored by beia_core's creative worker (headline, price, CTA,
// product image, palette, layout). This is NOT the editorial quote card; it is a
// direct-response offer card. New layouts are added here without touching beia_core.

type OfferCardProps = {
  headline: string;
  subhead?: string;
  price?: string;        // pre-formatted, e.g. "£24" or "From £9/mo"
  cta?: string;          // e.g. "Shop now", "Start free"
  productImage?: string; // absolute URL of the real product shot (optional)
  brandName?: string;
  accentColor?: string;
  background?: string;   // card background when there is no full-bleed image
  textColor?: string;
  layout?: 'image_top' | 'overlay' | 'text_only';
};

const OfferCard: React.FC<OfferCardProps> = ({
  headline,
  subhead,
  price,
  cta = 'Shop now',
  productImage,
  brandName = 'BEIA',
  accentColor = '#C0392B',
  background = '#FFFFFF',
  textColor = '#111111',
  layout,
}) => {
  const resolved: OfferCardProps['layout'] =
    layout || (productImage ? 'image_top' : 'text_only');
  const font = 'Arial, Helvetica, sans-serif';

  const Brand = (
    <p style={{ margin: 0, fontSize: 30, fontWeight: 700, letterSpacing: 2,
      color: accentColor, fontFamily: font, textTransform: 'uppercase' }}>
      {brandName}
    </p>
  );
  const Price = price ? (
    <span style={{ display: 'inline-block', background: accentColor, color: '#FFFFFF',
      fontSize: 44, fontWeight: 700, padding: '10px 28px', borderRadius: 12,
      fontFamily: font }}>{price}</span>
  ) : null;
  const Cta = (
    <span style={{ display: 'inline-block', background: textColor, color: background,
      fontSize: 38, fontWeight: 700, padding: '18px 44px', borderRadius: 60,
      fontFamily: font }}>{cta} →</span>
  );

  if (resolved === 'overlay' && productImage) {
    return (
      <AbsoluteFill style={{ backgroundColor: '#000' }}>
        <Img src={productImage} style={{ width: '100%', height: '100%', objectFit: 'cover' }} />
        <AbsoluteFill style={{
          background: 'linear-gradient(to bottom, rgba(0,0,0,0.15) 30%, rgba(0,0,0,0.82) 100%)',
        }} />
        <AbsoluteFill style={{ padding: 80, justifyContent: 'space-between' }}>
          <div>{Brand}</div>
          <div style={{ display: 'flex', flexDirection: 'column', gap: 28 }}>
            <p style={{ margin: 0, fontSize: 88, fontWeight: 700, lineHeight: 1.05,
              color: '#FFFFFF', fontFamily: font }}>{headline}</p>
            {subhead ? <p style={{ margin: 0, fontSize: 40, lineHeight: 1.25,
              color: 'rgba(255,255,255,0.92)', fontFamily: font }}>{subhead}</p> : null}
            <div style={{ display: 'flex', alignItems: 'center', gap: 28, marginTop: 8 }}>
              {Price}{Cta}
            </div>
          </div>
        </AbsoluteFill>
      </AbsoluteFill>
    );
  }

  if (resolved === 'image_top' && productImage) {
    return (
      <AbsoluteFill style={{ backgroundColor: background }}>
        <div style={{ height: '58%', width: '100%', backgroundColor: '#000' }}>
          <Img src={productImage} style={{ width: '100%', height: '100%', objectFit: 'cover' }} />
        </div>
        <div style={{ height: '42%', padding: 72, display: 'flex',
          flexDirection: 'column', justifyContent: 'space-between' }}>
          <div style={{ display: 'flex', flexDirection: 'column', gap: 20 }}>
            {Brand}
            <p style={{ margin: 0, fontSize: 66, fontWeight: 700, lineHeight: 1.08,
              color: textColor, fontFamily: font }}>{headline}</p>
            {subhead ? <p style={{ margin: 0, fontSize: 34, lineHeight: 1.25,
              color: 'rgba(17,17,17,0.7)', fontFamily: font }}>{subhead}</p> : null}
          </div>
          <div style={{ display: 'flex', alignItems: 'center', gap: 24 }}>{Price}{Cta}</div>
        </div>
      </AbsoluteFill>
    );
  }

  // text_only — bold typographic offer card, no product shot
  return (
    <AbsoluteFill style={{ backgroundColor: background, padding: 90,
      justifyContent: 'space-between' }}>
      <div>{Brand}</div>
      <div style={{ display: 'flex', flexDirection: 'column', gap: 32 }}>
        <p style={{ margin: 0, fontSize: 96, fontWeight: 700, lineHeight: 1.04,
          color: textColor, fontFamily: font }}>{headline}</p>
        {subhead ? <p style={{ margin: 0, fontSize: 42, lineHeight: 1.25,
          color: 'rgba(17,17,17,0.7)', fontFamily: font }}>{subhead}</p> : null}
      </div>
      <div style={{ display: 'flex', alignItems: 'center', gap: 28 }}>{Price}{Cta}</div>
    </AbsoluteFill>
  );
};

export const RemotionRoot: React.FC = () => {
  return (
    <>
    <Composition
      id="OfferCard"
      component={OfferCard}
      durationInFrames={1}
      fps={30}
      width={1080}
      height={1350}
      defaultProps={{
        headline: 'Your kitchen wall is boring. Here is the fix.',
        subhead: 'Neo-classical kitchen print, ready to hang.',
        price: '£24',
        cta: 'Shop now',
        brandName: 'Ruoth',
        accentColor: '#C0392B',
        background: '#FFFFFF',
        textColor: '#111111',
      }}
    />
    <Composition
      id="HookIntroReel"
      component={HookIntroReel}
      durationInFrames={INTRO_FRAMES + 300}
      fps={30}
      width={1080}
      height={1920}
      defaultProps={{
        hook: 'Still guessing this ingredient?',
        videoUrl: '',
        brandName: 'Ruoth',
        accentColor: '#C0392B',
      }}
      calculateMetadata={async ({ props }) => {
        const fps = 30;
        let vidFrames = 300; // 10s fallback if probing fails
        if (props.videoUrl) {
          try {
            const meta = await getVideoMetadata(props.videoUrl);
            vidFrames = Math.round(meta.durationInSeconds * fps);
          } catch (e) {
            // keep fallback — never fail the render on a probe error
          }
        }
        return { durationInFrames: INTRO_FRAMES + Math.max(1, vidFrames), fps };
      }}
    />
    <Composition
      id="TriviaReel"
      component={TriviaReel}
      durationInFrames={TRIVIA_INTRO_FRAMES + 240 + TRIVIA_OUTRO_FRAMES}
      fps={TRIVIA_FPS}
      width={1080}
      height={1920}
      defaultProps={{
        question: 'True or false: most home-based food businesses undercharge by 25–40%?',
        answer: 'True — and costing it properly is the fix.',
        pillar: 'Business & Costing',
        brandName: 'Ruoth',
        accentColor: '#C0392B',
        siteUrl: 'www.ruothstore.com',
        captions: [] as Caption[],
      }}
      calculateMetadata={({ props }) => {
        const caps = props.captions || [];
        const body = caps.length
          ? Math.round((caps[caps.length - 1].endMs / 1000) * TRIVIA_FPS)
          : 240;
        return {
          durationInFrames: TRIVIA_INTRO_FRAMES + Math.max(1, body) + TRIVIA_OUTRO_FRAMES,
          fps: TRIVIA_FPS,
        };
      }}
    />
    <Composition
      id="QuoteReel"
      component={QuoteVideo}
      durationInFrames={DEFAULT_IMAGES.length * CARD_DURATION}
      fps={30}
      width={1080}
      height={1920}
      defaultProps={{ images: DEFAULT_IMAGES, brandName: 'BEIA', accentColor: '#F97316' }}
      calculateMetadata={({ props }) => ({
        durationInFrames: Math.max(1, (props.images?.length || 1) * CARD_DURATION),
      })}
    />
    </>
  );
};
