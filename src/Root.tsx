// ── HookIntroReel ────────────────────────────────────────────────────────────
// The Ruoth (and any brand's) repurpose short: a ~3s white card with the hook
// typed in (typewriter), then the base campaign video cuts in. GENERIC — the hook
// text, the base video URL and the brand accent all come in as props from
// beia_core (the hook is generated by the scheduler; the base mp4 is the brand's
// asset). Nothing here is brand-specific.

const INTRO_FRAMES = 90; // 3s @ 30fps
const TYPE_FRAMES = 60;  // hook fully typed by 2s

type HookReelProps = {
  hook: string;
  videoUrl: string;
  brandName?: string;
  accentColor?: string;
  musicUrl?: string;     // royalty-free track baked over the whole reel (optional)
  musicVolume?: number;  // 0..1 (kept moderate so any clip audio still reads)
};

const TypewriterHook: React.FC<{ hook: string; accentColor: string }> = ({ hook, accentColor }) => {
  const frame = useCurrentFrame();
  const chars = Math.floor(
    interpolate(frame, [0, TYPE_FRAMES], [0, hook.length], {
      extrapolateLeft: 'clamp',
      extrapolateRight: 'clamp',
    })
  );
  const shown = hook.slice(0, chars);
  const cursorOn = Math.floor(frame / 8) % 2 === 0;
  return (
    <AbsoluteFill
      style={{
        backgroundColor: '#FFFFFF',
        alignItems: 'center',
        justifyContent: 'center',
        padding: 90,
      }}
    >
      <p
        style={{
          fontSize: 76,
          fontWeight: 700,
          color: '#111111',
          textAlign: 'center',
          lineHeight: 1.2,
          fontFamily: 'Arial, Helvetica, sans-serif',
          margin: 0,
        }}
      >
        {shown}
        <span style={{ color: accentColor, opacity: cursorOn ? 1 : 0 }}>|</span>
      </p>
    </AbsoluteFill>
  );
};

const HookIntroReel: React.FC<HookReelProps> = ({
  hook,
  videoUrl,
  accentColor = '#C0392B',
  musicUrl,
  musicVolume = 0.4,
}) => {
  return (
    <AbsoluteFill style={{ backgroundColor: '#FFFFFF' }}>
      {musicUrl ? <Audio src={resolveMedia(musicUrl)!} volume={musicVolume} loop /> : null}
      <Sequence durationInFrames={INTRO_FRAMES}>
        <TypewriterHook hook={hook} accentColor={accentColor} />
      </Sequence>
      <Sequence from={INTRO_FRAMES}>
        <AbsoluteFill style={{ backgroundColor: '#000000' }}>
          <OffthreadVideo
            src={videoUrl}
            style={{ width: '100%', height: '100%', objectFit: 'contain' }}
          />
        </AbsoluteFill>
      </Sequence>
    </AbsoluteFill>
  );
};

// ── HookImageReel ────────────────────────────────────────────────────────────
// The STILL-media sibling of HookIntroReel. Legacy campaigns (Ruoth's Launch
// Campaign) hold .jpg pins rather than .mp4 clips, so they can never satisfy a
// video-source composition — but they are still perfectly repurposable: the
// operator used to turn those stills into Shorts by hand. Same typed hook
// intro, then the still held with a slow Ken Burns push so it reads as motion.
// GENERIC — brand strings are props.

type HookImageReelProps = {
  hook: string;
  imageUrl: string;
  brandName?: string;
  accentColor?: string;
  musicUrl?: string;
  musicVolume?: number;
  holdSeconds?: number;
};

const IMAGE_HOLD_FRAMES = 240; // 8s @ 30fps

const HookImageReel: React.FC<HookImageReelProps> = ({
  hook,
  imageUrl,
  accentColor = '#C0392B',
  musicUrl,
  musicVolume = 0.4,
  holdSeconds,
}) => {
  const frame = useCurrentFrame();
  const hold = holdSeconds ? Math.round(holdSeconds * 30) : IMAGE_HOLD_FRAMES;
  const sinceImage = Math.max(0, frame - INTRO_FRAMES);
  // Slow push in — stills feel dead without movement on short-form.
  const scale = interpolate(sinceImage, [0, hold], [1, 1.08], {
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp',
  });

  return (
    <AbsoluteFill style={{ backgroundColor: '#FFFFFF' }}>
      {musicUrl ? <Audio src={resolveMedia(musicUrl)!} volume={musicVolume} loop /> : null}
      <Sequence durationInFrames={INTRO_FRAMES}>
        <TypewriterHook hook={hook} accentColor={accentColor} />
      </Sequence>
      <Sequence from={INTRO_FRAMES}>
        <AbsoluteFill
          style={{
            backgroundColor: '#000000',
            justifyContent: 'center',
            alignItems: 'center',
            overflow: 'hidden',
          }}
        >
          <Img
            src={imageUrl}
            style={{
              width: '100%',
              height: '100%',
              objectFit: 'contain',
              transform: `scale(${scale})`,
            }}
          />
        </AbsoluteFill>
      </Sequence>
    </AbsoluteFill>
  );
};

// ── TriviaReel ───────────────────────────────────────────────────────────────
// The CREATION surface (as opposed to HookIntroReel, which repurposes an
// existing clip). Manufactures a faceless trivia Short from text alone:
// branded intro -> question -> answer reveal -> CTA, narrated by a free
// CPU-only TTS voice with kinetic captions synced to it. GENERIC — every
// brand string comes in as a prop, so any brand reuses this composition.

type Caption = { text: string; startMs: number; endMs: number };

type TriviaReelProps = {
  question: string;
  answer: string;
  pillar?: string;
  narrationUrl?: string;   // absolute URL, else staticFile('narration.wav')
  captions?: Caption[];
  brandName?: string;
  accentColor?: string;
  logoUrl?: string;
  siteUrl?: string;
  musicUrl?: string;
  musicVolume?: number;
};

const TRIVIA_FPS = 30;
const TRIVIA_INTRO_FRAMES = 60;   // 2s branded intro
const TRIVIA_OUTRO_FRAMES = 60;   // 2s CTA end card

const KineticCaptions: React.FC<{ captions: Caption[]; accentColor: string }> = ({
  captions,
  accentColor,
}) => {
  const frame = useCurrentFrame();
  const ms = (frame / TRIVIA_FPS) * 1000;
  const active = captions.find((c) => ms >= c.startMs && ms <= c.endMs);
  if (!active) return null;

  // Pop in over the first 120ms of the caption.
  const since = ms - active.startMs;
  const scale = interpolate(since, [0, 120], [0.92, 1], {
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp',
  });

  return (
    <AbsoluteFill
      style={{
        justifyContent: 'flex-end',
        alignItems: 'center',
        paddingBottom: 320,
      }}
    >
      <div
        style={{
          transform: `scale(${scale})`,
          maxWidth: '84%',
          textAlign: 'center',
          fontFamily: 'Arial, Helvetica, sans-serif',
          fontSize: 62,
          fontWeight: 700,
          lineHeight: 1.25,
          color: '#FFFFFF',
          textShadow: '0 4px 18px rgba(0,0,0,0.55)',
          background: 'rgba(0,0,0,0.42)',
          borderRadius: 24,
          padding: '18px 30px',
          borderBottom: `6px solid ${accentColor}`,
        }}
      >
        {active.text}
      </div>
    </AbsoluteFill>
  );
};

const TriviaReel: React.FC<TriviaReelProps> = ({
  question,
  answer,
  pillar = '',
  narrationUrl,
  captions = [],
  brandName = 'Ruoth',
  accentColor = '#C0392B',
  logoUrl,
  siteUrl = '',
  musicUrl,
  musicVolume = 0.16,
}) => {
  const frame = useCurrentFrame();
  const font = 'Arial, Helvetica, sans-serif';

  // The voice reads the on-screen question and answer verbatim, so captioning
  // those same lines double-prints them. Captions exist for narration that ADDS
  // something ("Think about it."), not to echo text already on screen.
  const norm = (s: string) =>
    (s || '').toLowerCase().replace(/[^a-z0-9]/g, '');
  const onScreen = new Set([norm(question), norm(answer)]);
  const spokenOnly = captions.filter((c) => !onScreen.has(norm(c.text)));

  // Answer reveals for the last third of the narrated body.
  const narrationFrames = captions.length
    ? Math.round((captions[captions.length - 1].endMs / 1000) * TRIVIA_FPS)
    : 8 * TRIVIA_FPS;
  const revealAt = TRIVIA_INTRO_FRAMES + Math.round(narrationFrames * 0.62);
  const revealed = frame >= revealAt;

  const audioSrc = narrationUrl || staticFile('narration.wav');

  return (
    <AbsoluteFill style={{ backgroundColor: '#0E0E0E' }}>
      {musicUrl ? <Audio src={resolveMedia(musicUrl)!} volume={musicVolume} loop /> : null}
      <Sequence from={TRIVIA_INTRO_FRAMES}>
        <Audio src={audioSrc} />
      </Sequence>

      {/* Branded intro */}
      <Sequence durationInFrames={TRIVIA_INTRO_FRAMES}>
        <AbsoluteFill
          style={{
            backgroundColor: '#FFFFFF',
            justifyContent: 'center',
            alignItems: 'center',
            padding: 80,
          }}
        >
          {logoUrl ? (
            <Img src={logoUrl} style={{ width: 260, marginBottom: 40 }} />
          ) : null}
          <div
            style={{
              fontFamily: font,
              fontSize: 60,
              fontWeight: 700,
              color: '#111111',
              textAlign: 'center',
              letterSpacing: 2,
            }}
          >
            {brandName.toUpperCase()} RECIPE TRIVIA
          </div>
          {pillar ? (
            <div
              style={{
                fontFamily: font,
                fontSize: 40,
                marginTop: 20,
                color: accentColor,
                fontWeight: 600,
              }}
            >
              {pillar}
            </div>
          ) : null}
        </AbsoluteFill>
      </Sequence>

      {/* Question + answer reveal, captions over the top */}
      <Sequence from={TRIVIA_INTRO_FRAMES}>
        <AbsoluteFill
          style={{ padding: 80, justifyContent: 'center', paddingBottom: 420 }}
        >
          <div
            style={{
              fontFamily: font,
              fontSize: 68,
              fontWeight: 700,
              color: '#FFFFFF',
              lineHeight: 1.3,
              textAlign: 'center',
            }}
          >
            {question}
          </div>
          {revealed ? (
            <div
              style={{
                fontFamily: font,
                fontSize: 58,
                fontWeight: 700,
                color: accentColor,
                textAlign: 'center',
                marginTop: 60,
                background: 'rgba(255,255,255,0.96)',
                borderRadius: 20,
                padding: '24px 30px',
              }}
            >
              {answer}
            </div>
          ) : null}
        </AbsoluteFill>
        <KineticCaptions captions={spokenOnly} accentColor={accentColor} />
      </Sequence>

      {/* CTA end card */}
      <Sequence from={TRIVIA_INTRO_FRAMES + narrationFrames}>
        <AbsoluteFill
          style={{
            backgroundColor: '#FFFFFF',
            justifyContent: 'center',
            alignItems: 'center',
          }}
        >
          {logoUrl ? (
            <Img src={logoUrl} style={{ width: 300, marginBottom: 36 }} />
          ) : null}
          <div style={{ fontFamily: font, fontSize: 52, color: accentColor, fontWeight: 700 }}>
            {siteUrl}
          </div>
        </AbsoluteFill>
      </Sequence>
    </AbsoluteFill>
  );
};

